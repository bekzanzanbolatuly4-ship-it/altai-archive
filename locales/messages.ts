export function formatCity(city: string, locale: Locale): string {
  const c = city.trim().toLowerCase();
  if (c.includes('усть-каменогорск') || c.includes('өскемен') || c.includes('oskemen')) {
    return locale === 'kk' ? 'Өскемен' : locale === 'en' ? 'Oskemen' : 'Усть-Каменогорск';
  }
  if (c.includes('риддер') || c.includes('ridder')) {
    return locale === 'en' ? 'Ridder' : 'Риддер';
  }
  if (c.includes('зайсан') || c.includes('zaysan')) {
    return locale === 'en' ? 'Zaysan' : 'Зайсан';
  }
  return city;
}

export function formatRegion(locale: Locale): string {
  return locale === 'kk'
    ? 'Шығыс Қазақстан облысы'
    : locale === 'en'
    ? 'East Kazakhstan'
    : 'Восточно-Казахстанская область';
}

export function formatInstitutionName(locale: Locale): string {
  if (locale === 'kk') return 'Шығыс Қазақстан облысының мемлекеттік архиві';
  return 'Государственный архив Восточно-Казахстанской области';
}
